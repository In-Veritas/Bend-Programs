#!/usr/bin/env python3
"""Generate mechanical affine state accessors for the Leiden implementation.

No algorithm lives here. The generated module owns each array exactly once;
each read returns the state with the value, each write returns the new state.
Run from any directory with Python 3. All generated source remains reviewable.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
fields = {'rows': 'Array<List<&2, G.Nb>>', 'original_rows': 'Array<List<&2, G.Nb>>', 'groups': 'Array<List<&2, U32>>'}
uints = 'mem ref count stable added nonsingle order empty queue mapping orig newc amem'.split()
doubles = 'nw cw ext ewpc cum anw'.split()
for name in uints:
    fields[name] = 'Array<U32>'
for name in doubles:
    fields[name] = 'Array<F.D>'
fields.update(rh='U32', rl='U32', changed='Bool', err='Bool')

names = ', '.join(fields)
def record(replacements=None):
    replacements = replacements or {}
    return 'S{' + ', '.join(replacements.get(n, n) for n in fields) + '}'

out = ['# Generated by tools/generate_leiden_state.py. Do not hand-edit.\n',
       'import Base\nimport ./f64.bend as F\nimport ./cl_graph.bend as G\n',
       'type S is Type:\n  S{' + ', '.join(f'{n}: {t}' for n,t in fields.items()) + '}\n',
       '''def pair(-A: Type, -B: Type, -C: Type, p: A & B, k: A -> B -> C) -> C:
  (a, b) = p
  k(a)(b)
''']
for name, typ in fields.items():
    if typ.startswith('Array<'):
        value = typ[6:-1]
        out.append(f'''def {name}_get(s: S, +i: U32) -> S & {value}:
  match s:
    case {record()}:
      pair(Array<{value}>, {value}, S & {value}, Array.get({value}, {name}, i), a => v =>
        ({record({name: 'a'})}, v))

def {name}_set(s: S, +i: U32, v: {value}) -> S:
  match s:
    case {record()}:
      {record({name: f'Array.set({value}, {name}, i, v)'})}
''')
    else:
        pattern = record({name:'+'+name})
        out.append(f'''def {name}_get(s: S) -> S & {typ}:
  match s:
    case {pattern}:
      ({record()}, {name})

def {name}_set(s: S, v: {typ}) -> S:
  match s:
    case {record()}:
      {record({name: 'v'})}
''')
for name in doubles:
    for operation in ('add','sub'):
        out.append(f'''def {name}_{operation}(s: S, +i: U32, v: F.D) -> S:
  pair(S, F.D, S, {name}_get(s, i), s => old =>
    {name}_set(s, i, F.d_{operation}(old, v)))
''')

out.append('''def new(+n: U32, rows: Array<List<&2, G.Nb>>) -> S:
  +d = G.depth(n)
  pair(Array<List<&2, G.Nb>>, Array<List<&2, G.Nb>>, S,
    Array.clone(List<&2, G.Nb>, rows), rows => original_rows =>
  S{''' + ', '.join(
    name if name in ('rows','original_rows') else
    'Array.new(List<&2, U32>, d, Nil{})' if name=='groups' else
    'G.u32_array(n, 0)' if name in uints else
    'Array.new(F.D, d, F.D{0, 0})' if name in doubles else
    str(0x853c49e6) if name=='rh' else str(0x748fea9b) if name=='rl' else 'False{}'
    for name in fields) + '})\n')
out.append(f'''def reset_graph(s: S) -> S:
  match s:
    case {record()}:
      pair(Array<List<&2, G.Nb>>, Array<List<&2, G.Nb>>, S,
        Array.clone(List<&2, G.Nb>, original_rows), original_rows => rows =>
          {record()})

def replace_graph(s: S, g: Array<List<&2, G.Nb>>) -> S:
  match s:
    case {record()}:
      {record({'rows':'g'})}
''')
out.append(f'''def output(s: S) -> Array<U32>:
  match s:
    case {record()}:
      orig
''')
(ROOT/'cl_leiden_state.bend').write_text('\n'.join(out))
