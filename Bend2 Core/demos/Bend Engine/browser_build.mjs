import { spawnSync } from "node:child_process";
import { readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export function buildBrowser({ moduleUrl, source, target, globalName, metadata = {}, runtimeExports = {} }) {
  const here = dirname(fileURLToPath(moduleUrl));
  const core = resolve(process.env.BEND2_CORE || join(here, "../../../../bend2-core"));
  const temporary = join(process.env.TMPDIR || "/tmp", `bend2-core-${globalName.toLowerCase()}.generated.js`);
  const sourcePath = join(here, source), stagePath = join(here, `.browser-build-${process.pid}.bend`);
  const descriptors = Object.entries(runtimeExports).map(([name, descriptor]) => {
    if (typeof descriptor === "string") return { name, emitted: descriptor };
    return { name, ...descriptor };
  });
  const roots = descriptors.filter(descriptor => descriptor.bend).map(descriptor => {
    const root = `browser_export_${descriptor.name}_root_func`, sample = descriptor.sample || [];
    return [
      `assert ${root}:`,
      `  IO(${descriptor.returns})`,
      "",
      `def ${root}():`,
      `  IO.pure(${descriptor.returns}, ${descriptor.bend}!(${sample.join(", ")}))`,
    ].join("\n");
  });
  let emitted;
  try {
    // With no `main`, the current compiler roots every IO-returning definition.
    // The banged calls keep the pure browser entrypoints as named JS functions
    // instead of allowing whole-program inlining to erase the export boundary.
    const staged = readFileSync(sourcePath, "utf8")
      .replace(/^assert main:$/m, "assert browser_data_root_func:")
      .replace(/^def main\(\):$/m, "def browser_data_root_func():")
      + (roots.length ? `\n\n${roots.join("\n\n")}\n` : "");
    writeFileSync(stagePath, staged);
    const compile = spawnSync("bun", [join(core, "bend2/comp.ts"), stagePath, "--to", temporary], { cwd: core, encoding: "utf8" });
    if (compile.status !== 0) {
      process.stderr.write(compile.stdout);
      process.stderr.write(compile.stderr);
      process.exit(compile.status ?? 1);
    }
    emitted = readFileSync(temporary, "utf8");
  } finally {
    rmSync(stagePath, { force: true });
  }
  const footer = "cli(process.argv.slice(2));\nio_exit($main$);";
  const runtime = emitted.includes(footer) ? emitted.replace(footer, "") : emitted;
  if (!runtime.includes("function $main_value$(")) throw new Error("Bend JS output omitted the banged main_value browser root");
  for (const descriptor of descriptors) if (!runtime.includes(`function ${descriptor.emitted}(`)) throw new Error(`Bend JS output omitted live browser function ${descriptor.emitted}`);
  const exported = descriptors
    .map(({ name, emitted }) => `${JSON.stringify(name)}:(...args)=>run_loop(${emitted}(...args))`)
    .join(",");
  const exportLine = exported
    ? `\nglobalThis.${globalName}_CORE = Object.freeze({${exported}});`
    : "";
  const browser = `${runtime.trimEnd()}\n\nglobalThis.${globalName} = run_loop($main_value$());${exportLine}\nglobalThis.${globalName}_META = Object.freeze(${JSON.stringify({ compiler: "Bend2 Core", source, deterministic: true, ...metadata })});`;
  writeFileSync(join(here, target), "// Generated by build.mjs; do not hand-edit.\n" + browser);
  console.log(`${globalName} data written to ${join(here, target)}`);
}
